-- ShopDesk schema for Supabase (PostgreSQL)
-- Run this in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
--
-- The backend connects with the Postgres role from DATABASE_URL (the project
-- owner), which bypasses RLS. RLS is enabled below with no public policies so
-- requests using the public anon/authenticated API keys cannot read or write
-- these tables.

create table if not exists public.users (
  uid        bigint generated by default as identity primary key,
  uname      text        not null,
  email      text        not null unique,
  password   text        not null, -- bcrypt hash, never returned by the API
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  pid         bigint generated by default as identity primary key,
  pname       text        not null,
  description text        not null default '',
  price       numeric(12, 2) not null default 0 check (price >= 0),
  qty         integer     not null default 0 check (qty >= 0),
  created_at  timestamptz not null default now()
);

create table if not exists public.orders (
  oid        bigint generated by default as identity primary key,
  uid        bigint      not null,
  pid        bigint      not null,
  order_date timestamptz not null default now(),
  constraint orders_uid_fkey foreign key (uid)
    references public.users (uid)
    on delete cascade
    on update cascade,
  constraint orders_pid_fkey foreign key (pid)
    references public.products (pid)
    on delete restrict
    on update cascade
);

create index if not exists idx_orders_uid on public.orders (uid);
create index if not exists idx_orders_pid on public.orders (pid);
create index if not exists idx_orders_date on public.orders (order_date);

alter table public.users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;

-- The backend's Postgres role bypasses RLS as the table owner. No policies are
-- added on purpose: direct requests with the anon key are denied.

-- Ask PostgREST to pick up the new tables immediately.
notify pgrst, 'reload schema';
